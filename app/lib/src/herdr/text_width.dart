/// Width in terminal cells of a single [rune]: 2 if it falls in a
/// [_wideRanges] entry, else 1.
///
/// Deliberately an approximation of wcwidth(3): East Asian Ambiguous
/// characters are treated as narrow, and combining marks / zero-width
/// characters are not special-cased (they count as 1). Callers must degrade
/// safely on a mismatch -- in `stripPanelPadding` a mis-measured row merely
/// drops out of the panel-run grouping and is left untouched, never
/// corrupted.
int runeDisplayWidth(int rune) {
  var lo = 0;
  var hi = (_wideRanges.length >> 1) - 1;
  while (lo <= hi) {
    final mid = (lo + hi) >> 1;
    if (rune < _wideRanges[mid << 1]) {
      hi = mid - 1;
    } else if (rune > _wideRanges[(mid << 1) + 1]) {
      lo = mid + 1;
    } else {
      return 2;
    }
  }
  return 1;
}

/// Width in terminal cells of the visible string [s] (which must already be
/// free of ANSI escapes). Iterates runes, not UTF-16 code units, so non-BMP
/// characters are measured once, not per surrogate half.
int displayWidth(String s) {
  var width = 0;
  for (final rune in s.runes) {
    width += runeDisplayWidth(rune);
  }
  return width;
}
